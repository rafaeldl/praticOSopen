/// Spacing, sizes and radii of the PraticOS app design system.
class AppSpacing {
  AppSpacing._();

  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;

  /// Horizontal page margin for text content.
  static const double pageMargin = 24;

  /// Horizontal margin for full-width blocks and buttons.
  static const double blockMargin = 16;
}

class AppSizes {
  AppSizes._();

  /// The single primary button of a screen and the assistant bar buttons.
  static const double primaryButtonHeight = 58;

  /// Minimum height of any other touch target.
  static const double minTouchTarget = 44;
}

class AppRadii {
  AppRadii._();

  static const double button = 16;
  static const double block = 20;
  static const double field = 12;
}
