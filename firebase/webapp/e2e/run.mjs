// npm run e2e: builds the app for the emulators, starts the Emulator Suite on
// demo-praticos, seeds it and runs Playwright. Nothing here reaches real Firebase.
//
// Env:
//   PW_ARGS             arguments for `playwright test` (e.g. "e2e/auth.spec.ts e2e/team.spec.ts")
//   PW_WORKERS          Playwright workers (playwright.config.ts: 2 local, 3 on CI, 1 in perf)
//   E2E_ONLY            emulators to start (default auth,firestore,storage,functions)
//   E2E_ORDERS          orders the seed generates
//   E2E_SKIP_BUILD      reuse dist-e2e (rebuilt anyway when it was built for other ports)
//   E2E_PORT_OFFSET     move every emulator and the page server by this much. When unset,
//                       the offset comes from the machine slot: slot 0 = 1000, slot 1 = 2000...
//                       (never 0, so a run from an older branch on the default ports does not
//                       collide; if a port is taken anyway, the slot moves on by E2E_MAX_CONCURRENT
//                       x 1000). On CI it stays 0.
//   E2E_MAX_CONCURRENT  E2E runs at once on this machine (default 2). The others wait for a
//                       slot ("aguardando vaga de E2E…"). Locks: ~/.cache/praticos-e2e/slot-N.lock
//                       (E2E_LOCK_DIR), holding the PID; a lock whose process is gone is taken
//                       back. Not used on CI (env CI).
//   E2E_SLOT_TIMEOUT    minutes to wait for a slot before giving up (default 30)
//   E2E_JAVA_HEAP       max heap of the Firestore emulator (default 1g). Without it the JVM
//                       takes up to 1/4 of the RAM (12 GB seen on a 24 GB Mac).
//   E2E_SERVE_TTL       minutes `serve` (npm run emulators) stays up (default 30, 0 = no limit)
//
// Everything it starts runs in one process group (e2e/group.mjs). Ctrl+C, SIGTERM, SIGHUP,
// the parent process dying or this one being killed take the whole group down and remove
// the generated files (fake .secret.local, firebase.e2e.offset-<offset>.json, .env.e2e.local).
// Parallel test runs belong in different worktrees: dist-e2e and .env.e2e.local are per copy.
// The exit code is Playwright's.
import { execFileSync, spawn } from 'node:child_process'
import { closeSync, existsSync, mkdirSync, openSync, readFileSync, rmSync, statSync, writeFileSync, writeSync } from 'node:fs'
import { constants, homedir } from 'node:os'
import { createServer } from 'node:net'
import { join, resolve } from 'node:path'

const webapp = resolve(import.meta.dirname, '..')
const functionsDir = resolve(webapp, '../functions')
const only = process.env.E2E_ONLY ?? 'auth,firestore,storage,functions'
const perf = process.argv[2] === 'perf'
// `serve` leaves the suite up, seeded, for npm run dev.
const serve = process.argv[2] === 'serve'
const usesFunctions = only.includes('functions')
const MARK = '# generated by e2e/run.mjs, removed when it ends'
const sleep = (ms) => new Promise((done) => setTimeout(done, ms))
const log = (message) => console.log(`[e2e] ${message}`)
// A closed terminal must not crash this process before it takes the group down.
process.stdout.on('error', () => {})
process.stderr.on('error', () => {})

if (usesFunctions && !existsSync(resolve(functionsDir, 'lib/index.js'))) {
  console.error('Functions sem build. Rode em firebase/functions: npm ci && npm run build')
  process.exit(1)
}

// --- Cleanup, signals and the parent watch --------------------------------

const generated = []
const secretFile = resolve(functionsDir, '.secret.local')
let createdSecrets = false
let slotFile = null
let group = null // the e2e/group.mjs child currently running
let stopping = false

function groupAlive(pid) {
  try {
    process.kill(-pid, 0)
    return true
  } catch {
    return false
  }
}

function killGroup(pid, signal) {
  try {
    process.kill(-pid, signal)
  } catch {}
}

function removeFiles() {
  generated.forEach((file) => rmSync(file, { force: true }))
  generated.length = 0
  if (createdSecrets) rmSync(secretFile, { force: true })
  createdSecrets = false
  if (slotFile && lockHolder(slotFile)?.pid === process.pid) rmSync(slotFile, { force: true })
  slotFile = null
}

// Last resort when the process exits on any path.
process.on('exit', () => {
  if (group?.pid) killGroup(group.pid, 'SIGKILL')
  removeFiles()
})

async function stopGroup() {
  const pid = group?.pid
  if (!pid) return
  killGroup(pid, 'SIGTERM')
  for (let i = 0; i < 40 && groupAlive(pid); i++) await sleep(250)
  if (groupAlive(pid)) killGroup(pid, 'SIGKILL')
}

async function shutdown(reason, code) {
  if (stopping) return
  stopping = true
  log(`${reason}: encerrando os emuladores e o Playwright`)
  await stopGroup()
  removeFiles()
  process.exit(code)
}

for (const signal of ['SIGINT', 'SIGTERM', 'SIGHUP']) {
  process.on(signal, () => shutdown(`recebeu ${signal}`, 128 + constants.signals[signal]))
}

// An agent that kills npm (or times out) leaves this process with another parent.
const parent = process.ppid
setInterval(() => {
  if (process.ppid !== parent) shutdown('o processo pai morreu', 1)
}, 2000).unref()

// Runs a command in its own process group, led by e2e/group.mjs.
function runInGroup(command, args, env = process.env) {
  return new Promise((done) => {
    const child = spawn(process.execPath, [resolve(webapp, 'e2e/group.mjs'), String(process.pid), command, ...args], {
      cwd: webapp,
      stdio: 'inherit',
      detached: true,
      // What e2e/group.mjs removes if this process is killed without cleaning up.
      env: { ...env, E2E_GROUP_CLEANUP: JSON.stringify([...generated, ...(createdSecrets ? [secretFile] : []), ...(slotFile ? [slotFile] : [])]) },
    })
    group = child
    child.on('exit', async (code, signal) => {
      const pid = child.pid
      // Anything still in the group (a Chrome that ignored SIGTERM) goes now.
      for (let i = 0; i < 12 && groupAlive(pid); i++) await sleep(250)
      if (groupAlive(pid)) killGroup(pid, 'SIGKILL')
      group = null
      done(code ?? (signal ? 128 + constants.signals[signal] : 1))
    })
  })
}

// --- Machine slot: at most E2E_MAX_CONCURRENT runs at once -----------------

function startTime(pid) {
  try {
    return execFileSync('ps', ['-o', 'lstart=', '-p', String(pid)], { encoding: 'utf8' }).trim()
  } catch {
    return ''
  }
}

function lockHolder(file) {
  try {
    return JSON.parse(readFileSync(file, 'utf8'))
  } catch (error) {
    if (error.code === 'ENOENT') return null
    // Half-written by someone taking it right now; garbage after a few seconds.
    try {
      return Date.now() - statSync(file).mtimeMs < 10_000 ? { pid: -1, writing: true } : { pid: 0 }
    } catch {
      return null
    }
  }
}

// Same PID and the same start time: a reused PID does not hold the slot.
const holderAlive = (holder) => holder?.writing || (holder?.pid > 0 && startTime(holder.pid) === holder.started)

async function tryTake(file, me) {
  let holder = lockHolder(file)
  if (holder && !holderAlive(holder)) {
    // Check again right before removing it: someone else may have just taken it back.
    holder = lockHolder(file)
    if (holder && !holderAlive(holder)) rmSync(file, { force: true })
  }
  try {
    const fd = openSync(file, 'wx')
    writeSync(fd, JSON.stringify(me))
    closeSync(fd)
  } catch (error) {
    if (error.code === 'EEXIST') return false
    throw error
  }
  // Two processes cleaning the same stale lock: only the one whose PID stayed in it wins.
  await sleep(300)
  return lockHolder(file)?.pid === process.pid
}

// Every port of firebase.e2e.json plus the page server, moved by offset.
const baseConfig = JSON.parse(readFileSync(resolve(webapp, '../firebase.e2e.json'), 'utf8'))
const portsFor = (offset) => [4183, ...Object.values(baseConfig.emulators).map((value) => value?.port).filter(Boolean)].map((port) => port + offset)

// firebase-tools wants the port free on 127.0.0.1 and on ::1 (when the machine has IPv6).
function portFreeOn(port, host) {
  return new Promise((done) => {
    const server = createServer()
    server.once('error', (error) => done(error.code === 'EADDRNOTAVAIL' || error.code === 'EAFNOSUPPORT'))
    server.listen(port, host, () => server.close(() => done(true)))
  })
}
const portFree = async (port) => (await portFreeOn(port, '127.0.0.1')) && (await portFreeOn(port, '::1'))

// Slot i owns the offsets (i + 1) * 1000, (i + 1 + slots) * 1000... up to 9000. Steps of
// 1000 because the base ports sit 100 apart (19099, 19199, 19299...): a step of 100 or 200
// puts one run's auth on another's storage. The next offset of the slot is used when a
// port is taken by something else (a run with E2E_PORT_OFFSET, an older branch).
async function freeOffset(slot, slots) {
  for (let offset = (slot + 1) * 1000; offset <= 9000; offset += slots * 1000) {
    const free = await Promise.all(portsFor(offset).map(portFree))
    if (free.every(Boolean)) return offset
  }
  return null
}

async function takeSlot(fixedOffset) {
  const dir = process.env.E2E_LOCK_DIR ?? join(homedir(), '.cache/praticos-e2e')
  mkdirSync(dir, { recursive: true })
  const slots = Math.max(1, Number(process.env.E2E_MAX_CONCURRENT) || 2)
  const timeout = Number(process.env.E2E_SLOT_TIMEOUT ?? 30) * 60_000
  const me = { pid: process.pid, started: startTime(process.pid), dir: webapp, mode: process.argv[2] ?? 'e2e', since: new Date().toISOString() }
  const holders = () =>
    Array.from({ length: slots }, (_, slot) => lockHolder(join(dir, `slot-${slot}.lock`)))
      .map((holder, slot) => holder && `vaga ${slot}: ${holder.mode} pid ${holder.pid} em ${holder.dir}`)
      .filter(Boolean)
      .join('; ')
  const begin = Date.now()
  let lastNotice = 0
  const warned = new Set()
  while (!stopping) {
    for (let slot = 0; slot < slots; slot++) {
      const file = join(dir, `slot-${slot}.lock`)
      if (!(await tryTake(file, me))) continue
      slotFile = file
      const offset = fixedOffset ?? (await freeOffset(slot, slots))
      if (offset !== null) return { slot, offset }
      if (!warned.has(slot)) log(`vaga ${slot} livre, mas as portas dela estão ocupadas por outro processo`)
      warned.add(slot)
      rmSync(file, { force: true })
      slotFile = null
    }
    if (Date.now() - begin > timeout) {
      console.error(`[e2e] nenhuma vaga de E2E em ${timeout / 60_000} min (E2E_SLOT_TIMEOUT). ${holders()}`)
      process.exit(1)
    }
    if (Date.now() - lastNotice > 60_000) {
      lastNotice = Date.now()
      log(`aguardando vaga de E2E… (no máximo ${slots} ao mesmo tempo, E2E_MAX_CONCURRENT; ${holders()})`)
    }
    await sleep(5000)
  }
  return new Promise(() => {}) // shutdown() exits
}

// --- The run ----------------------------------------------------------------

const fixed = process.env.E2E_PORT_OFFSET ? Number(process.env.E2E_PORT_OFFSET) : undefined
let offset = fixed ?? 0
if (!process.env.CI) {
  const taken = await takeSlot(fixed)
  offset = taken.offset
  log(`vaga ${taken.slot} da máquina, portas +${offset}`)
}

// Files a killed run may have left: ours carry MARK.
const envLocal = resolve(webapp, '.env.e2e.local')
for (const file of [envLocal, secretFile]) {
  if (existsSync(file) && readFileSync(file, 'utf8').startsWith(MARK)) rmSync(file, { force: true })
}

// Own ports: a copy of firebase.e2e.json and an .env.e2e.local for the build, both removed at the end.
let config = '../firebase.e2e.json'
if (offset) {
  const base = JSON.parse(readFileSync(resolve(webapp, config), 'utf8'))
  const port = (name) => base.emulators[name].port
  for (const [, value] of Object.entries(base.emulators)) if (value?.port) value.port += offset
  config = `../firebase.e2e.offset-${offset}.json`
  writeFileSync(resolve(webapp, config), JSON.stringify(base, null, 2))
  writeFileSync(
    envLocal,
    [
      MARK,
      `VITE_API_BASE_URL=http://127.0.0.1:${port('functions')}/demo-praticos/southamerica-east1/api`,
      `VITE_EMULATOR_AUTH_PORT=${port('auth')}`,
      `VITE_EMULATOR_FIRESTORE_PORT=${port('firestore')}`,
      `VITE_EMULATOR_STORAGE_PORT=${port('storage')}`,
      '',
    ].join('\n'),
  )
  generated.push(resolve(webapp, config), envLocal)
  process.env.PW_PORT = String(4183 + offset)
  process.env.E2E_FIRESTORE_PORT = String(port('firestore'))
}

// dist-e2e has the emulator ports baked in: it is reused only when built for this offset.
const stamp = resolve(webapp, 'dist-e2e/.e2e-port-offset')
const builtFor = existsSync(stamp) ? Number(readFileSync(stamp, 'utf8')) : existsSync(resolve(webapp, 'dist-e2e')) ? 0 : NaN
if (process.env.E2E_SKIP_BUILD && builtFor !== offset && !serve) {
  log(`dist-e2e foi gerado para as portas +${builtFor || 0}, não +${offset}: gerando de novo`)
}
if (!serve && (!process.env.E2E_SKIP_BUILD || builtFor !== offset)) {
  const status = await runInGroup('npm', ['run', 'build:e2e'])
  if (stopping) await new Promise(() => {})
  if (status !== 0) process.exit(status)
  writeFileSync(stamp, String(offset))
}

// The functions bind secrets at load. Fake values, removed afterwards; a real
// local file is left alone (it is git-ignored and never read here).
if (usesFunctions && !existsSync(secretFile)) {
  createdSecrets = true
  writeFileSync(
    secretFile,
    [
      MARK,
      `ASAAS_CREDENTIALS_KEY=${Buffer.alloc(32).toString('base64')}`,
      'REVENUECAT_WEBHOOK_AUTH=fake',
      'REVENUECAT_SECRET_API_KEY=fake',
      'SSR_API_SECRET=fake',
      'ANTHROPIC_API_KEY=fake',
      '',
    ].join('\n'),
  )
}

const test = serve
  ? `node -e "setInterval(() => {}, 1 << 30)"`
  : perf
    ? `E2E_PERF=1 ${process.env.PERF_COLD ? 'PERF_COLD=1 ' : ''}npx playwright test e2e/perf`
    : `npx playwright test ${process.env.PW_ARGS ?? ''}`

if (serve) {
  const ttl = Number(process.env.E2E_SERVE_TTL ?? 30)
  if (ttl > 0) {
    log(`o serve fica de pé por ${ttl} min (E2E_SERVE_TTL; 0 = sem limite)`)
    setTimeout(() => shutdown(`E2E_SERVE_TTL de ${ttl} min venceu`, 0), ttl * 60_000).unref()
  }
}

// The Firestore emulator is the only JVM; JAVA_TOOL_OPTIONS reaches it through firebase-tools.
const heap = process.env.E2E_JAVA_HEAP ?? '1g'
const javaOptions = [process.env.JAVA_TOOL_OPTIONS, `-Xmx${heap}`].filter(Boolean).join(' ')
const status = await runInGroup(
  'npx',
  ['firebase', 'emulators:exec', '--config', config, '--project', 'demo-praticos', '--only', only, `node e2e/seed.mjs && ${test}`],
  { ...process.env, JAVA_TOOL_OPTIONS: javaOptions },
)
if (stopping) await new Promise(() => {})
removeFiles()
process.exit(status)
