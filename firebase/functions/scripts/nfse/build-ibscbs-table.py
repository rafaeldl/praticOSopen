"""
Builds src/services/nfse/layouts/ibscbs-table.ts from the government's
correlation table (Anexo VIII: item LC 116 x NBS x cIndOp x cClassTrib), so the
2027 layout can fill IBSCBS without asking the owner for tax codes.

Usage (openpyxl needed):
  python3 scripts/nfse/build-ibscbs-table.py anexo_viii-tabela-correlacao-v01-02-00-20261026.xlsx

Source: https://www.gov.br/nfse/pt-br/biblioteca/documentacao-tecnica/rtc
The sheet uses merged cells: a value applies to the rows below it until the
next value in the same column (item, NBS and Simples activity), and extra
cIndOp/cClassTrib rows add options to the NBS above them.
"""

import json
import os
import re
import sys

import openpyxl

SOURCE = os.path.basename(sys.argv[1])
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'services', 'nfse', 'layouts', 'ibscbs-table.ts')


def code(value, size):
    text = re.sub(r'\D', '', str(value or ''))
    return text.zfill(size) if text else ''


def main():
    ws = openpyxl.load_workbook(sys.argv[1], read_only=True, data_only=True)['tabela geral']
    by_nbs = {}
    order = []
    item = activity = nbs = None
    for i, row in enumerate(ws.iter_rows(values_only=True)):
        if i == 0:
            continue
        item_cell, _, nbs_cell, _, activity_cell, _, op_cell, _, class_cell = (list(row) + [None] * 9)[:9]
        if item_cell:
            item = str(item_cell).strip()
            activity = None
            nbs = None
        if activity_cell:
            activity = code(activity_cell, 2)
        if nbs_cell:
            previous = by_nbs.get(nbs) if nbs else None
            nbs = code(nbs_cell, 9)
            key = (item, nbs)
            if key not in by_nbs:
                by_nbs[key] = {'item': item, 'nbs': nbs, 'activity': activity, 'ops': [], 'classes': []}
                order.append(key)
            entry = by_nbs[key]
            # An NBS row without its own codes keeps the ones of the NBS above it.
            if previous and not op_cell:
                entry['ops'] = list(previous['ops'])
            if previous and not class_cell:
                entry['classes'] = list(previous['classes'])
            nbs = key
        if not nbs:
            continue
        entry = by_nbs[nbs]
        if op_cell:
            op = code(op_cell, 6)
            if op not in entry['ops']:
                entry['ops'].append(op)
        if class_cell:
            cls = code(class_cell, 6)
            if cls not in entry['classes']:
                entry['classes'].append(cls)

    rows = []
    for key in order:
        e = by_nbs[key]
        if not e['ops'] or not e['classes']:
            continue
        rows.append([e['item'], e['nbs'], e['activity'] or '', ' '.join(e['ops']), ' '.join(e['classes'])])

    body = ',\n'.join('  ' + json.dumps(r, ensure_ascii=False) for r in rows)
    with open(OUT, 'w', encoding='utf-8') as out:
        out.write(
            f'// Generated by scripts/nfse/build-ibscbs-table.py from {SOURCE}. Do not edit.\n'
            '// [item LC 116, NBS, cAtvSN, cIndOp options, cClassTrib options]; first option is the usual one.\n'
            f"export const IBSCBS_TABLE_SOURCE = {json.dumps(SOURCE)};\n"
            'export const IBSCBS_TABLE: ReadonlyArray<readonly [string, string, string, string, string]> = [\n'
            f'{body},\n];\n'
        )
    print(f'{len(rows)} rows -> {os.path.normpath(OUT)}')


if __name__ == '__main__':
    main()
