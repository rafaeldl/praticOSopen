/**
 * Regenerates src/services/nfse/icp-brasil-intermediates.ts from the ITI
 * package of every accredited AC (ACcompactado.zip).
 *
 *   curl -sSLO https://acraiz.icpbrasil.gov.br/credenciadas/CertificadosAC-ICP-Brasil/ACcompactado.zip
 *   unzip -d acs ACcompactado.zip
 *   npx ts-node scripts/nfse/update-icp-brasil-intermediates.ts acs <sha256 of the zip>
 *
 * Keeps only CA certificates still valid today whose chain, inside the
 * package, ends in one of the pinned roots (icp-brasil-roots.ts). Roots,
 * expired ACs and anything that does not chain are left out. See
 * docs/NFSE_DIRECT.md ("ACs intermediárias").
 */

import { X509Certificate } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ICP_BRASIL_ROOTS } from '../../src/services/nfse/icp-brasil-roots';

const [dir, zipSha] = process.argv.slice(2);
if (!dir) {
  console.error('usage: update-icp-brasil-intermediates.ts <dir> [zip sha256]');
  process.exit(1);
}

const now = new Date();
const roots = ICP_BRASIL_ROOTS.map((pem) => new X509Certificate(pem));
const all = readdirSync(dir)
  .filter((f) => /\.(crt|cer|pem|der)$/i.test(f))
  .map((f) => {
    try {
      return new X509Certificate(readFileSync(join(dir, f)));
    } catch {
      console.warn(`skip (unreadable): ${f}`);
      return null;
    }
  })
  .filter((c): c is X509Certificate => !!c);

const valid = (c: X509Certificate) => now >= new Date(c.validFrom) && now <= new Date(c.validTo);
const isRoot = (c: X509Certificate) => roots.some((r) => r.fingerprint256 === c.fingerprint256) || c.checkIssued(c);
const candidates = all.filter((c) => c.ca && valid(c) && !isRoot(c));

/** True when [cert] reaches a pinned root through other candidates. */
function chains(cert: X509Certificate, depth = 0): boolean {
  if (depth > 6) return false;
  if (roots.some((r) => valid(r) && cert.checkIssued(r) && cert.verify(r.publicKey))) return true;
  return candidates.some((c) => c !== cert && cert.checkIssued(c) && cert.verify(c.publicKey) && chains(c, depth + 1));
}

const seen = new Set<string>();
const kept = candidates
  .filter((c) => chains(c))
  .filter((c) => (seen.has(c.fingerprint256) ? false : (seen.add(c.fingerprint256), true)))
  .sort((a, b) => a.subject.localeCompare(b.subject));

const cn = (c: X509Certificate) => c.subject.split('\n').find((l) => l.startsWith('CN='))?.slice(3) ?? c.subject;
const body = kept
  .map((c) => `  // ${cn(c)}, valid until ${c.validTo}, SHA-256 ${c.fingerprint256}\n  \`${c.toString().trim()}\`,`)
  .join('\n');

const today = now.toISOString().slice(0, 10);
const out = `/**
 * Intermediate ACs of the ICP-Brasil (every AC accredited under the pinned
 * roots), from the ITI package
 * https://acraiz.icpbrasil.gov.br/credenciadas/CertificadosAC-ICP-Brasil/ACcompactado.zip
 * downloaded on ${today}${zipSha ? ` (zip SHA-256 ${zipSha})` : ''}.
 *
 * Used only to complete the chain of an A1 whose .pfx brings just the holder's
 * certificate: the chain must still end in a root of icp-brasil-roots.ts and
 * every link is checked (signature, CA flag, validity). Nothing is fetched
 * from the internet at upload time.
 *
 * GENERATED by scripts/nfse/update-icp-brasil-intermediates.ts: do not edit
 * by hand. Kept ${kept.length} of ${all.length} certificates (CA, valid on ${today},
 * chaining to a pinned root). Regenerate when the ITI accredits a new AC or
 * renews one (docs/NFSE_DIRECT.md).
 */

export const ICP_BRASIL_INTERMEDIATES: readonly string[] = [
${body}
];
`;
writeFileSync(join(__dirname, '../../src/services/nfse/icp-brasil-intermediates.ts'), out);
console.log(`kept ${kept.length} of ${all.length}`);
