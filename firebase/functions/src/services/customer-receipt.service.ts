/**
 * "Receber de João" through the server, for a consultant who includes orders
 * of the customer that someone else created ("Outras OS de João").
 *
 * The Firestore rules only let a consultant update the orders they created,
 * so the app sends this case here; financial roles keep the offline batch of
 * the app. Same writes as the app's `buildReceiptPlan`: per order a regular
 * `payment` transaction `{receiptId}_{n}` with `paidAt` and `receiptGroupId`
 * (plus a receipt OrderDocument when a file was attached), and the Receipt
 * `companies/{cid}/receipts/{receiptId}` created by the user. Only payment
 * fields are written, in one transaction, after checking every order.
 */
import { db } from './firestore.service';
import { applyPaymentTransaction, calculateRemainingBalance } from './order.service';
import type { Order, PaymentTransaction, UserAggr } from '../models/types';
import { AsaasServiceError } from './asaas/errors';
import { toCents } from '../utils/payment-allocation';

export const MAX_RECEIPT_ORDERS = 50;
const ID_PATTERN = /^[A-Za-z0-9_-]{1,128}$/;
const FINANCIAL_ROLES = ['owner', 'admin', 'manager'];
const FILE_TYPES = /^(image\/[a-z0-9.+-]+|application\/pdf)$/;

export interface ReceiptFileInput {
  url: string;
  storagePath: string;
  fileName?: string;
  contentType: string;
}

export interface CustomerReceiptInput {
  /** Generated by the app (the file is uploaded under it before saving). */
  receiptId: string;
  /** ISO date-time the money came in. */
  paidAt: string;
  /** Oldest first, as the screen split it. */
  allocations: Array<{ orderId: string; amount: number }>;
  receiptFile?: ReceiptFileInput;
}

export interface OpenOrderSummary {
  id: string;
  number: number | null;
  open: number;
  createdAt: string | null;
  /** Created by the user asking (the consultant's own order). */
  own: boolean;
}

/** Financial roles receive on any order; a consultant, when the company uses values. */
export function canReceiveForCustomer(role: string | undefined, useFinancial: boolean | undefined): boolean {
  if (useFinancial === false) return false;
  return !!role && (FINANCIAL_ROLES.includes(role) || role === 'consultant');
}

function isPayable(order: Pick<Order, 'status'>): boolean {
  return order.status !== 'quote' && order.status !== 'canceled';
}

function toIso(value: unknown): string | null {
  if (!value) return null;
  if (typeof value === 'string') return value;
  if (typeof (value as { toDate?: () => Date }).toDate === 'function') {
    return (value as { toDate: () => Date }).toDate().toISOString();
  }
  if (value instanceof Date) return value.toISOString();
  return null;
}

function ordersRef(companyId: string) {
  return db.collection('companies').doc(companyId).collection('orders');
}

/**
 * Open orders of a customer: only id, number, open amount, date and whether
 * it is the user's own. Oldest first. One equality filter: no index.
 */
export async function listCustomerOpenOrders(
  companyId: string,
  customerId: string,
  userId: string,
): Promise<OpenOrderSummary[]> {
  const snapshot = await ordersRef(companyId).where('customer.id', '==', customerId).get();
  return snapshot.docs
    .map((doc) => ({ ...(doc.data() as Order), id: doc.id }))
    .filter((order) => isPayable(order) && calculateRemainingBalance(order) > 0)
    .map((order) => ({
      id: order.id,
      number: order.number ?? null,
      open: calculateRemainingBalance(order),
      createdAt: toIso(order.createdAt),
      own: order.createdBy?.id === userId,
    }))
    .sort((a, b) => (a.createdAt ?? '').localeCompare(b.createdAt ?? '') || (a.number ?? 0) - (b.number ?? 0));
}

function validateFile(companyId: string, receiptId: string, file: ReceiptFileInput | undefined): void {
  if (!file) return;
  const prefix = `tenants/${companyId}/receipts/${receiptId}/`;
  let url: URL | null = null;
  try {
    url = new URL(file.url);
  } catch {
    url = null;
  }
  if (
    typeof file.storagePath !== 'string' ||
    !file.storagePath.startsWith(prefix) ||
    file.storagePath.includes('..') ||
    !url ||
    url.protocol !== 'https:' ||
    !FILE_TYPES.test(file.contentType ?? '')
  ) {
    throw new AsaasServiceError('INVALID_FILE', 'Invalid receipt file');
  }
}

function validatePaidAt(paidAt: string): string {
  const date = new Date(paidAt);
  const tomorrow = Date.now() + 24 * 60 * 60 * 1000;
  if (Number.isNaN(date.getTime()) || date.getTime() > tomorrow) {
    throw new AsaasServiceError('INVALID_PAID_AT', 'Invalid payment date');
  }
  return date.toISOString();
}

export async function registerCustomerReceipt(
  companyId: string,
  customerId: string,
  input: CustomerReceiptInput,
  user: UserAggr,
): Promise<{ receiptId: string; amount: number }> {
  if (!ID_PATTERN.test(input.receiptId)) throw new AsaasServiceError('INVALID_VALUE', 'Invalid receipt id');
  const allocations = input.allocations ?? [];
  const ids = allocations.map((a) => a.orderId);
  if (
    allocations.length === 0 ||
    allocations.length > MAX_RECEIPT_ORDERS ||
    new Set(ids).size !== ids.length ||
    ids.some((id) => !ID_PATTERN.test(id)) ||
    allocations.some((a) => !(toCents(a.amount) > 0))
  ) {
    throw new AsaasServiceError('INVALID_VALUE', 'Invalid allocations');
  }
  const paidAt = validatePaidAt(input.paidAt);
  validateFile(companyId, input.receiptId, input.receiptFile);

  const receiptRef = db.collection('companies').doc(companyId).collection('receipts').doc(input.receiptId);

  return db.runTransaction(async (tx) => {
    const receiptSnap = await tx.get(receiptRef);
    const orderSnaps = await Promise.all(ids.map((id) => tx.get(ordersRef(companyId).doc(id))));
    if (receiptSnap.exists) throw new AsaasServiceError('RECEIPT_EXISTS', 'Receipt already registered');

    const orders = orderSnaps.map((snap) => {
      if (!snap.exists) throw new AsaasServiceError('ORDER_NOT_FOUND', 'Order not found');
      const order = { ...(snap.data() as Order), id: snap.id };
      if (order.customer?.id !== customerId) {
        throw new AsaasServiceError('ORDER_NOT_OF_CUSTOMER', 'Order belongs to another customer');
      }
      if (!isPayable(order)) throw new AsaasServiceError('ORDER_NOT_PAYABLE', 'Quotes and canceled orders cannot receive');
      return order;
    });
    allocations.forEach((a, i) => {
      if (toCents(a.amount) > toCents(calculateRemainingBalance(orders[i]))) {
        throw new AsaasServiceError('VALUE_EXCEEDS_BALANCE', 'Value exceeds the open amount of an order');
      }
    });

    const now = new Date().toISOString();
    const actor = { id: user.id, name: user.name };
    const file = input.receiptFile;
    let totalCents = 0;
    const receiptAllocations = allocations.map((a, i) => {
      const order = orders[i];
      const amount = toCents(a.amount) / 100;
      const transaction: PaymentTransaction = {
        id: `${input.receiptId}_${i}`,
        type: 'payment',
        amount,
        createdAt: now,
        createdBy: actor,
        paidAt,
        receiptGroupId: input.receiptId,
      };
      const update: Record<string, unknown> = {};
      if (file) {
        const documentId = `receipt_${input.receiptId}_${i}`;
        transaction.receiptDocumentId = documentId;
        const documents = ((order as unknown as { documents?: unknown[] }).documents ?? []) as unknown[];
        update.documents = [...documents, {
          id: documentId,
          url: file.url,
          storagePath: file.storagePath,
          fileName: file.fileName ?? null,
          contentType: file.contentType,
          type: 'receipt',
          createdAt: now,
          createdBy: actor,
          linkedTransactionId: transaction.id,
        }];
      }
      const result = applyPaymentTransaction(order, transaction);
      tx.update(ordersRef(companyId).doc(order.id), {
        ...update,
        transactions: result.transactions,
        paidAmount: result.paidAmount,
        paid: result.paid,
        payment: result.payment,
        updatedAt: now,
        updatedBy: actor,
      });
      totalCents += toCents(amount);
      return { orderId: order.id, orderNumber: order.number ?? null, amount, transactionId: transaction.id };
    });

    const amount = totalCents / 100;
    tx.set(receiptRef, {
      id: input.receiptId,
      company: { id: companyId },
      customer: orders[0].customer ? { id: customerId, name: orders[0].customer.name ?? null } : { id: customerId },
      amount,
      paidAt,
      ...(file ? { receiptFile: { ...file, fileName: file.fileName ?? null } } : {}),
      allocations: receiptAllocations,
      status: 'active',
      createdAt: now,
      createdBy: actor,
      updatedAt: now,
      updatedBy: actor,
    });
    return { receiptId: input.receiptId, amount };
  });
}
