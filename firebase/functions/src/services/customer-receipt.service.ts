export interface ReceiptAllocation {
  orderId: string;
  orderNumber?: number | null;
  amount: number;
  transactionId?: string;
}

export interface CustomerReceipt {
  id: string;
  customer?: { id: string; name?: string | null };
  amount: number;
  paidAt?: string;
  paymentMethod?: string;
  receiptFile?: Omit<ReceiptFileInput, 'fileName'> & { fileName?: string | null };
  allocations: ReceiptAllocation[];
  status: 'active' | 'canceled';
  createdAt?: string;
  createdBy?: UserAggr;
  updatedAt?: string;
  updatedBy?: UserAggr;
}

/** Who sees, undoes and changes the proof of [receipt]: financial access, or who registered it. */
export type ReceiptAccess = (receipt: Pick<CustomerReceipt, 'createdBy'>) => boolean;

function receiptsRef(companyId: string) {
  return db.collection('companies').doc(companyId).collection('receipts');
}

/**
 * Active receipts of a customer that [canSee] lets through, newest first (by
 * the day the money came in). One equality filter: no composite index.
 */
export async function listCustomerReceipts(
  companyId: string,
  customerId: string,
  canSee: ReceiptAccess,
  includeCanceled = false,
): Promise<CustomerReceipt[]> {
  const snapshot = await receiptsRef(companyId).where('customer.id', '==', customerId).get();
  return snapshot.docs
    .map((doc) => ({ ...(doc.data() as CustomerReceipt), id: doc.id }))
    .filter((r) => (includeCanceled || r.status === 'active') && canSee(r))
    .sort((a, b) => (b.paidAt ?? b.createdAt ?? '').localeCompare(a.paidAt ?? a.createdAt ?? ''));
}

async function readReceipt(
  tx: FirebaseFirestore.Transaction,
  companyId: string,
  customerId: string,
  receiptId: string,
  canManage: ReceiptAccess,
) {
  const ref = receiptsRef(companyId).doc(receiptId);
  const snap = await tx.get(ref);
  const receipt = snap.exists ? ({ ...(snap.data() as CustomerReceipt), id: snap.id }) : null;
  if (!receipt || receipt.customer?.id !== customerId) throw new AsaasServiceError('RECEIPT_NOT_FOUND', 'Receipt not found');
  if (!canManage(receipt)) throw new AsaasServiceError('FORBIDDEN', 'Not allowed on this receipt');
  return { ref, receipt };
}

/** The receipt's orders as they are now (missing ones are left out). */
async function readAllocatedOrders(tx: FirebaseFirestore.Transaction, companyId: string, receipt: CustomerReceipt) {
  const ids = [...new Set((receipt.allocations ?? []).map((a) => a.orderId).filter(Boolean))];
  const snaps = await Promise.all(ids.map((id) => tx.get(ordersRef(companyId).doc(id))));
  return new Map(snaps.filter((s) => s.exists).map((s) => [s.id, { ...(s.data() as Order), id: s.id }]));
}

/**
 * "Desfazer recebimento": the receipt turns `canceled` and each order loses
 * its share (same math as removing one payment by hand). The shared file
 * stays in Storage; its OrderDocument leaves each order. Asaas receipts
 * (`asaas_*`) are undone only with a refund in Asaas.
 */
export async function cancelCustomerReceipt(
  companyId: string,
  customerId: string,
  receiptId: string,
  user: UserAggr,
  canManage: ReceiptAccess,
): Promise<CustomerReceipt> {
  return db.runTransaction(async (tx) => {
    const { ref, receipt } = await readReceipt(tx, companyId, customerId, receiptId, canManage);
    if (receiptId.startsWith(ASAAS_TRANSACTION_PREFIX)) {
      throw new AsaasServiceError('ASAAS_LOCKED', 'A receipt of an Asaas payment is undone with a refund in Asaas');
    }
    if (receipt.status === 'canceled') return receipt;
    const orders = await readAllocatedOrders(tx, companyId, receipt);
    const now = new Date().toISOString();
    const actor = { id: user.id, name: user.name };

    for (const allocation of receipt.allocations ?? []) {
      const order = orders.get(allocation.orderId);
      const transactions = order?.transactions ?? [];
      const index = transactions.findIndex((t) => t.id === allocation.transactionId);
      if (!order || index < 0) continue;
      const share = transactions[index];
      const remaining = transactions.filter((_, i) => i !== index);
      const paidAmount = Math.max(0, roundMoney((Number(order.paidAmount) || 0) - share.amount));
      const documents = order.documents ?? [];
      const kept = documents.filter((d) => d.linkedTransactionId !== share.id && d.id !== share.receiptDocumentId);
      const update: Record<string, unknown> = {
        transactions: remaining,
        paidAmount,
        ...paymentStatusFields(order.status, Number(order.total) || 0, paidAmount),
        updatedAt: now,
        updatedBy: actor,
        ...(kept.length !== documents.length ? { documents: kept } : {}),
      };
      orders.set(order.id, { ...order, ...update } as Order);
      tx.update(ordersRef(companyId).doc(order.id), update);
    }
    const receiptUpdate = { status: 'canceled' as const, updatedAt: now, updatedBy: actor };
    tx.update(ref, receiptUpdate);
    return { ...receipt, ...receiptUpdate };
  });
}

/**
 * Attaches ([file]) or removes (null) the proof of a receipt: on the receipt
 * and, as an OrderDocument linked to the share, on every order it covers.
 * The file is shared, so removing it never deletes it from Storage.
 */
export async function setCustomerReceiptFile(
  companyId: string,
  customerId: string,
  receiptId: string,
  file: ReceiptFileInput | null,
  user: UserAggr,
  canManage: ReceiptAccess,
): Promise<CustomerReceipt> {
  if (file) validateFile(companyId, receiptId, file);
  return db.runTransaction(async (tx) => {
    const { ref, receipt } = await readReceipt(tx, companyId, customerId, receiptId, canManage);
    if (receiptId.startsWith(ASAAS_TRANSACTION_PREFIX)) {
      throw new AsaasServiceError('ASAAS_LOCKED', 'A receipt of an Asaas payment has the receipt of Asaas');
    }
    if (receipt.status === 'canceled') throw new AsaasServiceError('RECEIPT_CANCELED', 'The receipt was undone');
    const orders = await readAllocatedOrders(tx, companyId, receipt);
    const now = new Date().toISOString();
    const actor = { id: user.id, name: user.name };

    (receipt.allocations ?? []).forEach((allocation, i) => {
      const order = orders.get(allocation.orderId);
      const transactions = [...(order?.transactions ?? [])];
      const index = transactions.findIndex((t) => t.id === allocation.transactionId);
      if (!order || index < 0) return;
      const share = { ...transactions[index] };
      const documentId = share.receiptDocumentId ?? `receipt_${receiptId}_${i}`;
      const documents = (order.documents ?? []).filter((d) => d.id !== documentId && d.linkedTransactionId !== share.id);
      delete share.receiptDocumentId;
      if (file) {
        share.receiptDocumentId = documentId;
        documents.push({
          id: documentId,
          url: file.url,
          storagePath: file.storagePath,
          fileName: file.fileName ?? null,
          contentType: file.contentType,
          type: 'receipt',
          createdAt: now,
          createdBy: actor,
          linkedTransactionId: share.id,
        });
      }
      transactions[index] = share;
      const update = { transactions, documents, updatedAt: now, updatedBy: actor };
      orders.set(order.id, { ...order, ...update } as Order);
      tx.update(ordersRef(companyId).doc(order.id), update);
    });
    tx.update(ref, {
      receiptFile: file ? { ...file, fileName: file.fileName ?? null } : FieldValue.delete(),
      updatedAt: now,
      updatedBy: actor,
    });
    const next = { ...receipt, updatedAt: now, updatedBy: actor } as CustomerReceipt;
    if (file) next.receiptFile = { ...file, fileName: file.fileName ?? null };
    else delete next.receiptFile;
    return next;
  });
}
